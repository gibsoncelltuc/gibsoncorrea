"""Episódios 11 a 30 (dados). Cada episódio: 6 clipes de 10 s = 60 s. Refrão nos clipes 1, 4 e 6.
Campos de cada clipe: chars, cam, img (primeiro quadro), a (3 fases: 0-3 s | 3-7 s | 7-10 s), sfx, l1/l2 (letra PT), e1/e2 (legenda EN).
Regras de segurança já embutidas: ações lentas e pequenas; poucos objetos; nada assustador; nenhuma criança sem roupa;
adulto só como coruja (Olívia); nada de carro andando; fogão só ao fundo com linha de segurança.
"""


def S(chars, cam, img, a, sfx, l1, l2, e1, e2):
    p = [x.strip() for x in a.split("|")]
    assert len(p) == 3, a
    return dict(chars=chars, cam=cam, img=img, a=p, sfx=sfx, l1=l1, l2=l2, e1=e1, e2=e2)


